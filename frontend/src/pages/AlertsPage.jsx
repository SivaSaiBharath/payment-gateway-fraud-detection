import { useCallback, useEffect, useState } from 'react';
import PageHeader from '../components/common/PageHeader.jsx';
import Notice from '../components/common/Notice.jsx';
import DataTable from '../components/common/DataTable.jsx';
import JsonResult from '../components/common/JsonResult.jsx';
import SectionCard from '../components/layout/SectionCard.jsx';
import { alertsApi } from '../services/alertsApi.js';
import { getErrorMessage } from '../services/api.js';
import { asArray } from '../utils/format.js';

export default function AlertsPage() {
  const [rows, setRows] = useState([]);
  const [lookupId, setLookupId] = useState('');
  const [loading, setLoading] = useState(false);
  const [busy, setBusy] = useState(false);
  const [notice, setNotice] = useState(null);
  const [result, setResult] = useState(undefined);

  const load = useCallback(async () => {
    setLoading(true); setNotice(null);
    try { setRows(asArray((await alertsApi.list()).data)); }
    catch (e) { setRows([]); setNotice({ type: 'error', text: getErrorMessage(e) }); }
    finally { setLoading(false); }
  }, []);
  useEffect(() => { load(); }, [load]);

  async function lookup(e) {
    e.preventDefault(); if (!lookupId.trim()) return;
    setBusy(true); setNotice(null); setResult(undefined);
    try { setResult((await alertsApi.getById(lookupId.trim())).data); setNotice({ type: 'success', text: 'Alert lookup request succeeded.' }); }
    catch (e) { setNotice({ type: 'error', text: `${getErrorMessage(e)}. Note: the supplied controller declares the path variable as Iterable<Long>; verify this endpoint in Spring Boot.` }); }
    finally { setBusy(false); }
  }

  return (
    <>
      <PageHeader eyebrow="RISK MONITORING" title="Fraud alerts" description="Review alert records generated by your fraud detection backend." action={<button className="secondary-button" onClick={load}>Refresh alerts</button>} />
      {notice && <Notice type={notice.type} onClose={() => setNotice(null)}>{notice.text}</Notice>}
      <SectionCard title="Find alert" subtitle="GET /Alerts/{id} — controller signature should be verified">
        <form className="inline-form" onSubmit={lookup}><label className="field-label" htmlFor="alert-id">Alert ID</label><input id="alert-id" type="number" min="1" value={lookupId} onChange={(e) => setLookupId(e.target.value)} placeholder="Enter alert ID" required /><button className="primary-button" disabled={busy}>Find alert</button></form>
        <JsonResult title="Alert lookup response" data={result} />
      </SectionCard>
      <SectionCard title="All fraud alerts" subtitle="GET /Alerts">
        <DataTable rows={rows} loading={loading} emptyText="No alerts found, or the API is not reachable." />
      </SectionCard>
    </>
  );
}